namespace Microsoft.EntityFrameworkCore.Query.Internal;

/// <summary>
///     A single element of a query batch: either a query producing a result set, or a captured
///     'ExecuteDelete'/'ExecuteUpdate' operation whose rows-affected count is surfaced as a result set.
/// </summary>
/// <remarks>
///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
///     the same compatibility standards as public APIs. It may be changed or removed without notice in
///     any release. You should only use it directly in your code with extreme caution and knowing that
///     doing so can result in application failures when updating to a new Entity Framework Core release.
/// </remarks>
public sealed class RelationalBatchElement
{
    private readonly IRelationalBatchQueryingEnumerable? _queryingEnumerable;
    private readonly RelationalCommandResolver? _commandResolver;

    /// <summary>
    ///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
    ///     the same compatibility standards as public APIs. It may be changed or removed without notice in
    ///     any release. You should only use it directly in your code with extreme caution and knowing that
    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    public RelationalBatchElement(IRelationalBatchQueryingEnumerable queryingEnumerable)
    {
        _queryingEnumerable = queryingEnumerable;
        QueryContext = queryingEnumerable.QueryContext;
        ThreadSafetyChecksEnabled = queryingEnumerable.ThreadSafetyChecksEnabled;
    }

    /// <summary>
    ///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
    ///     the same compatibility standards as public APIs. It may be changed or removed without notice in
    ///     any release. You should only use it directly in your code with extreme caution and knowing that
    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    public RelationalBatchElement(
        RelationalQueryContext queryContext,
        RelationalCommandResolver commandResolver,
        bool threadSafetyChecksEnabled)
    {
        _commandResolver = commandResolver;
        QueryContext = queryContext;
        ThreadSafetyChecksEnabled = threadSafetyChecksEnabled;
    }

    /// <summary>
    ///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
    ///     the same compatibility standards as public APIs. It may be changed or removed without notice in
    ///     any release. You should only use it directly in your code with extreme caution and knowing that
    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    public RelationalQueryContext QueryContext { get; }

    /// <summary>
    ///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
    ///     the same compatibility standards as public APIs. It may be changed or removed without notice in
    ///     any release. You should only use it directly in your code with extreme caution and knowing that
    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    public bool ThreadSafetyChecksEnabled { get; }

    /// <summary>
    ///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
    ///     the same compatibility standards as public APIs. It may be changed or removed without notice in
    ///     any release. You should only use it directly in your code with extreme caution and knowing that
    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    public bool IsNonQuery
        => _queryingEnumerable == null;

    /// <summary>
    ///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
    ///     the same compatibility standards as public APIs. It may be changed or removed without notice in
    ///     any release. You should only use it directly in your code with extreme caution and knowing that
    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    public bool DetailedErrorsEnabled
        => _queryingEnumerable?.DetailedErrorsEnabled ?? false;

    /// <summary>
    ///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
    ///     the same compatibility standards as public APIs. It may be changed or removed without notice in
    ///     any release. You should only use it directly in your code with extreme caution and knowing that
    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    public IReadOnlyList<ReaderColumn?>? ReaderColumns
        => _queryingEnumerable?.ReaderColumns;

    /// <summary>
    ///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
    ///     the same compatibility standards as public APIs. It may be changed or removed without notice in
    ///     any release. You should only use it directly in your code with extreme caution and knowing that
    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    public IRelationalCommandTemplate ResolveCommandTemplate()
        => _queryingEnumerable?.ResolveCommandTemplate() ?? _commandResolver!(QueryContext.Parameters);

    /// <summary>
    ///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
    ///     the same compatibility standards as public APIs. It may be changed or removed without notice in
    ///     any release. You should only use it directly in your code with extreme caution and knowing that
    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    public IEnumerator<T> MaterializeResultSet<T>(RelationalDataReader dataReader)
        => _queryingEnumerable is { } queryingEnumerable
            ? queryingEnumerable.MaterializeResultSet<T>(dataReader)
            : throw new InvalidOperationException(RelationalStrings.BatchQueryExpectedRowsAffected);

    /// <summary>
    ///     This is an internal API that supports the Entity Framework Core infrastructure and not subject to
    ///     the same compatibility standards as public APIs. It may be changed or removed without notice in
    ///     any release. You should only use it directly in your code with extreme caution and knowing that
    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    public IAsyncEnumerator<T> MaterializeResultSetAsync<T>(RelationalDataReader dataReader, CancellationToken cancellationToken)
        => _queryingEnumerable is { } queryingEnumerable
            ? queryingEnumerable.MaterializeResultSetAsync<T>(dataReader, cancellationToken)
            : throw new InvalidOperationException(RelationalStrings.BatchQueryExpectedRowsAffected);
}
